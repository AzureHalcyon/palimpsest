"""编写 `[W]` —— 把"这一刻取用的几件事"整理成**一段回忆**（第一人称），交给底座模型。

═══════════════════════════════════════════════════════════════════════
作者口径（2026-10-17）：**「原来的条目变成一段」** · **「编写的时候，把原文和节点强度给编写模型」**
　　　　　　　　　　　　　　**「加一个能点进去的按钮，看到用哪些条目、怎么编写」**
　　　　　　　　　　　　　　**「这个编写也存」**
═══════════════════════════════════════════════════════════════════════

## 这一步在流水线里的位置

    取件（[R]，只提候选/排序） → **[W] 编写** → 一段文字 → 进上下文
                              ↓
                          落 `说/`（模型生成过的东西必须留档：温度 >0 ⇒ 重跑拿不到同一份）

## 纪律（都不是猜的，见 `docs/流程框架.md §六`）

| 纪律 | 为什么 |
|---|---|
| **不给情境**（不把她这一轮听到的那句话喂进来） | 实测：给了 ⇒ 它把线索原样抄进输出 |
| **不带编号**（输入用 `·`，输出里不许出现序号/分条） | 实测：带编号 ⇒ 出口变成清单（编号是内部结构） |
| ★★ **⛔ 不许照抄**（"只写最清楚的那几处"） | 实测（2026-10-18，`缓存/说/` 里 52 条真记录）：原来写「用原文里的说法，**不加解释、不总结**」 ⇒ **输出 ＝ 素材**（6 件 494/492、7 件 574/575、10 件 982/974，中位 579 字，最高 1.18 倍）。那不是"一段回忆"，是**把对话缝了一遍** |

★★ **稿子形状（作者口径 2026-10-18）**：**不管取到几件，都融成一段**，第一人称；
  ⛔ 不是"一件事一句"的清单，⛔ 也不是复述问答。`条目文本` 因此**平铺、不分组**。

★★ **强度就是"写什么"的唯一指示**（作者原话）：
  > **「激活亮度就是最好的什么该写什么不该写的指示啊？给整段全文，那这段才激活一半，
  > 剩下一半是为了完整才给出的，不是让照着抄的」**

  所以**取材集是整组**（为了让她看得懂当时怎么回事），但**写进去的只是亮的那几处**；
  数小的那些可以不出现 —— 这不是"丢件"，是"想不起来"。明令 ⛔ 不许把数写进回忆：
  这是"给模型的读数"，不是"给人看的记录"。
  （界线沿用 `开工清单 §5` 第 6 条：**给人看的记录不许变成喂给模型的东西**；反过来，
   这里给模型的是**取用本身的读数**，不是记录层的编号。）
★★ **旧规作废**：「每一件都要说到，一件都不许省」（当年看到"4 件只用了 2 件"就以为
  是它在偷懒；现在知道**那是按亮度挑的**，只是那时没逐行给强度）。
"""
import io
import json
import os
import time
from typing import Dict, List, Optional

from .knobs import 编写 as K写

# ⛔ 这两段是**逐字定过的**，改动要么有实测依据，要么先问作者。
# ★★ 2026-10-18（第 14 场实测 + 作者口径「并入这个操作，得很肯定再做」）：
#   判定与编写**拆成两次调用**：
#   · `判定提示词`（温度 0）：只回答「这批旧记录要不要并进他这一句」。只认**指回**
#     （「就是那只」「那个角」），拿不准一律「无」。
#   · `编写提示词`：**不给情境**（旧规，给了它会抄线索），只把素材写成一段；每段带**时间**。
#   为什么拆：同一次调用里「既判又写」会偏松 —— 实测第 1 轮他明明没指回旧事，它也写了；
#   而 0.7 温度下同一份材料两次判出不同结果（第 12 轮一次有、一次无）。
#   ★ 时间标记治的是另一个病：第 6 轮她说「「也没什么」这话你今天第二回了」——
#     本场他只说过一次，旧场那几句被编写算成了「今天」。
from . import 提示词库


def _对方名() -> str:
    try:
        from .knobs import 对方名
        return 对方名()
    except Exception:                                    # noqa: BLE001
        return "对方"


def 编写模型() -> str:
    """编写 / 判定用哪个模型：`编写.模型`；空 = 跟对话模型一样（返回空串，交给 llm 默认）。"""
    return str(K写.get("模型", {}).get("值") or "").strip()


def 场时(场id: str) -> str:
    """`2026-10-17-09` → `10月17日 第9场`。认不出就返回空串（调用方据此不写时间）。"""
    import re
    m = re.match(r"(\d{4})-(\d{1,2})-(\d{1,2})-(\d+)", str(场id or ""))
    if not m:
        return ""
    return "%d月%d日 第%d场" % (int(m.group(2)), int(m.group(3)), int(m.group(4)))

# 模型说"没有"的几种常见形态（它不该编，所以这个分支得留）
没有的说法 = ("没有", "没有。", "无", "无。", "（没有）", "(没有)", "没有要回忆的", "没有要回忆的。")


def 条目文本(件们: List[Dict]) -> str:
    """一句话一行：`<强度> · <原文>`。强度缺省就不写那个数（⛔ 不编一个）。

    ★ 2026-10-18：**平铺，⛔ 分组、⛔ 空行** —— 作者口径是"不管几件都融成**一段**"，
      空行/组号会把模型推向"一件一条"的清单（那正好是错的那一版）。
      每行的强度才是"写不写它"的唯一指示。
    """
    行: List[str] = []
    for it in 件们:
        文本 = str(it.get("文本") or it.get("text") or "").strip()
        if not 文本:
            continue
        强度 = it.get("强度", it.get("score"))
        # ★★ 2026-10-18：每行先写**它是哪天的**（旧记录），⛔ 不能让它被当成"今天"。
        时 = 场时(it.get("场") or it.get("场id") or "")
        前 = ("%s ｜ " % 时) if 时 else ""
        if isinstance(强度, (int, float)):
            行.append("%s%.2f · %s" % (前, float(强度), 文本))
        else:
            行.append(前 + "· " + 文本)
    return "\n".join(行)


def 判定(llm, 件们: List[Dict], 线索: str, 温度: Optional[float] = None) -> Dict:
    """**这批旧记录要不要并进他这一句** —— 只认指回，拿不准 = 不并。

    ★ 2026-10-18：从 `编写` 里**拆出来单独一次调用**（温度 0）。
      合在一起时它会替"写"找理由 —— 第 1 轮他明明只说「路上看见一只猫」，它也写了。

    返回 `{"有": bool, "回答": str, "调用": {}, "耗时ms", "err"?}`；⛔ 不抛
    （判定挂了 = 这一轮不并：作者口径「很肯定才并」，失败不是肯定）。
    """
    t0 = time.time()
    try:
        提示 = 提示词库.填("写-判定", 素材=条目文本(件们),
                        现在=(str(线索 or "").strip() or "（这一轮他没说什么）"),
                        用户=_对方名())
        温度 = float(K写["判定温度"]["值"] if 温度 is None else 温度)
        msg = llm.chat([{"role": "user", "content": 提示}], temp=温度, fast=True,
                       model=(编写模型() or None))
        文 = str(msg.get("content") or "").strip()
        首 = (文.splitlines() or [""])[0]
        # 只认首行：模型不许把理由混进答案；写成别的措辞也按「有/无」判。
        有 = bool("有" in 首 and "无" not in 首)
        调用 = dict(msg.get("_call") or {})
        调用.update({"用途": "判定", "请求": [{"role": "user", "content": 提示}]})
        return {"有": 有, "回答": 文, "调用": 调用,
                "耗时ms": int((time.time() - t0) * 1000)}
    except Exception as e:                           # noqa: BLE001
        return {"有": False, "回答": "", "调用": {}, "耗时ms": int((time.time() - t0) * 1000),
                "err": "%s: %s" % (type(e).__name__, e)}


def 编写(llm, 件们: List[Dict], 场id: str = "", 轮: int = 0, 线索: str = "",
         温度: Optional[float] = None, 判定结果: Optional[Dict] = None) -> Dict:
    """把件写成一段回忆。

    返回：`{"ok", "编写", "没有", "耗时ms", "提示词哈希", "版本"}`。
    ⛔ **失败不许抛**：编写挂了，这一轮顶多"没想起什么"，不能把对话弄断
      （`ok=False` 时调用方决定是退回条目清单还是干脆不注入）。
    """
    from .film import 提示词哈希
    t0 = time.time()
    件们 = [x for x in (件们 or []) if str(x.get("文本") or x.get("text") or "").strip()]
    if not 件们:
        return {"ok": True, "编写": "", "没有": True, "耗时ms": 0,
                "提示词哈希": "", "版本": {}, "件数": 0, "判定": {}}
    # ★★ 2026-10-18：先判「要不要并进他这一句」——不并就当作"没想起什么"。
    #   `判定结果` 可注入（对照/测试用，免得为了验编写再打一次网络）。
    判 = 判定结果 if 判定结果 is not None else 判定(llm, 件们, 线索)
    if not 判.get("有"):
        return {"ok": True, "编写": "", "没有": True,
                "耗时ms": int((time.time() - t0) * 1000),
                "提示词哈希": "", "版本": {}, "件数": len(件们), "判定": 判}
    提示 = 提示词库.填("写-编写", 条目=条目文本(件们), 用户=_对方名())
    try:
        消息 = [{"role": "user", "content": 提示}]
        # ★ 要 logprobs：编写也是**模型生成过的东西**，它的 token 概率一样不可再生成。
        # ★ 2026-10-17（审查抓到）：0.7 原来是**硬编码裸值** ⇒ 提到 `knobs.编写["温度"]`
        温度 = float(K写["温度"]["值"] if 温度 is None else 温度)
        msg = llm.chat(消息, temp=温度, logprobs=True, fast=True,
                       model=(编写模型() or None))   # ★ 关思考：编写只要一段话，不需要那 900 个推理 token
        文本 = str(msg.get("content") or "").strip()
        # ★ 「全流程全记录」：这一次编写调用也要能落进那一轮的 调用[]
        调用 = dict(msg.get("_call") or {})
        调用.update({"用途": "编写", "请求": 消息, "请求条数": len(消息),
                     "usage": dict(getattr(llm, "last_usage", None) or {}),
                    "输出": {"content": 文本,
                            "reasoning": str(msg.get("reasoning_content") or ""),
                            "tool_calls": []},
                    "logprobs": msg.get("logprobs") or {}})
        if not 文本:
            # ★ 推理模型的老坑：`max_tokens` 被推理吃光 ⇒ 正文空。
            #   那不是"没有要回忆的"，是**这次没写成** ⇒ 如实报失败，让调用方退回去。
            return {"ok": False, "编写": "", "没有": False, "耗时ms": int((time.time() - t0) * 1000),
                    "提示词哈希": 提示词哈希(提示), "版本": {}, "件数": len(件们),
                    "调用": 调用, "err": "正文是空的（可能被推理吃光）"}
        没有 = 文本.strip(" \n。.!！") in [x.strip(" \n。.!！") for x in 没有的说法]
        out = {"ok": True, "编写": "" if 没有 else 文本, "没有": 没有, "调用": 调用,
               "判定": 判,
               "耗时ms": int((time.time() - t0) * 1000),
               "提示词哈希": 提示词哈希(提示), "件数": len(件们),
               "版本": {"提示词哈希": 提示词哈希(提示), "模型": 模型名(llm)}}
        return out
    except Exception as e:                           # noqa: BLE001
        return {"ok": False, "编写": "", "没有": False, "耗时ms": int((time.time() - t0) * 1000),
                "提示词哈希": "", "版本": {}, "件数": len(件们),
                "err": "%s: %s" % (type(e).__name__, e)}


def 模型名(llm) -> str:
    前 = getattr(llm, "cfg", None) or getattr(llm, "cfg", None)
    return str(getattr(前, "model", "") or "")


def 记说(cache_dir: str, 场id: str, 轮: int, 线索: str, 件们: List[Dict],
        结果: Dict) -> None:
    """落 `<cache>/说/<场id>.jsonl` —— **编写这一步的输出必须留档**。

    为什么：温度 >0 ⇒ 重跑拿不到同一份；而没有它，"改编写提示词前后"就没法比。
    """
    try:
        os.makedirs(os.path.join(cache_dir, "说"), exist_ok=True)
        行 = {"场id": str(场id), "轮": int(轮), "线索": str(线索 or ""),
              "给了哪些": [{"件id": it.get("件id"), "文本": str(it.get("文本") or it.get("text") or ""),
                            "强度": it.get("强度", it.get("score"))} for it in (件们 or [])],
              "编写": 结果.get("编写") or "",
              "没有": bool(结果.get("没有")),
              # ★ 2026-10-18：判定也是一次模型输出，要能事后看出"为什么不并"。
              "判定": {"有": bool((结果.get("判定") or {}).get("有")),
                       "回答": str((结果.get("判定") or {}).get("回答") or "")},
              "编写版本": dict(结果.get("版本") or {}),
              "耗时ms": int(结果.get("耗时ms") or 0),
              "时间": time.time()}
        with io.open(os.path.join(cache_dir, "说", 场id + ".jsonl"), "a", encoding="utf-8") as fh:
            fh.write(json.dumps(行, ensure_ascii=False) + "\n")
    except Exception:                                # noqa: BLE001
        pass           # ⛔ 记数据失败不许打断对话
