def 参数账() -> Dict[str, Dict]:
    """拍平成一页：`{组.名: {值, 依据, 说明, 无读者?}}` —— 写进日志、或给人核对用。"""
    账: Dict[str, Dict] = {}
    for 组, d in 全部.items():
        for k, v in d.items():
            p = "%s.%s" % (组, k)
            账[p] = dict(v)
            if p in 死旋钮:
                账[p]["无读者"] = 死旋钮[p]
    return 账


