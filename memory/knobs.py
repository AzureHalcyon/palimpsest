def 覆盖文件() -> str:
    return os.path.join(_账目录(), "参数账覆盖.json")


def 记录文件() -> str:
    return os.path.join(_账目录(), "参数账改动.jsonl")


def 读覆盖() -> Dict[str, object]:
    """读 `参数账覆盖.json`。没有 / 坏了 ⇒ 空表（不抛：账读不出来不该让 App 起不来）。"""
    p = 覆盖文件()
    try:
        if not os.path.exists(p):
            return {}
        with open(p, encoding="utf-8") as f:
            d = json.load(f)
        return {str(k): v for k, v in (d or {}).items()} if isinstance(d, dict) else {}
    except Exception as exc:                             # noqa: BLE001
        import sys as _s
        print("[knobs] 覆盖读不出来（%s）：%s" % (p, type(exc).__name__), file=_s.stderr)
        return {}


def _按类型转(p: str, 新值: object):
    """把界面来的值转成**原来那个类型**。转不了就抛 `ValueError`（带人话）。"""
    现 = 参数账()[p]["值"]
    if isinstance(现, bool):
        if isinstance(新值, bool):
            return 新值
        s = str(新值).strip().lower()
        if s in ("true", "1", "开", "yes", "y", "on"):
            return True
        if s in ("false", "0", "关", "no", "n", "off"):
            return False
        raise ValueError("这一项只有 开 / 关")
    if isinstance(现, int):
        try:
            f = float(str(新值).strip())
        except (TypeError, ValueError):
            raise ValueError("这一项要是整数")
        if not (f == f and abs(f) != float("inf")):       # NaN / inf
            raise ValueError("这一项要是整数")
        if int(f) != f:
            raise ValueError("这一项要是整数（现在是 %s）" % 新值)
        return int(f)
    if isinstance(现, float):
        try:
            f = float(str(新值).strip())
        except (TypeError, ValueError):
            raise ValueError("这一项要是数字")
        if f != f or abs(f) == float("inf"):
            raise ValueError("这一项要是有限的数字")
        return float(f)
    s = str(新值 or "").strip()
    # ★ 2026-10-18：默认值本来就是空串的那一格（`编写.模型`：空 = 跟对话一样）
    #   必须**能清空**，否则一旦填过就再也回不到"跟对话一样"。
    if not s and str(_默认值.get(p, "")).strip():
        raise ValueError("这一项不能为空")
    return s


def 存覆盖(p: str, 新值: object) -> Dict:
    """改一项：校验 → 写覆盖 → 立刻生效（改内存里那格）→ 记一行。"""
    p = str(p or "")
    账 = 参数账()
    if p not in 账:
        return {"ok": False, "err": "没有这一项：%s" % p}
    if p in 死旋钮:
        # 死旋钮也能改（账上留着那一行），但得说清楚它现在没有读者 —— 改了不会有效果。
        pass
    旧 = 账[p]["值"]
    try:
        新 = _按类型转(p, 新值)
    except ValueError as e:
        return {"ok": False, "err": str(e)}
    表 = 读覆盖()
    表[p] = 新
    try:
        os.makedirs(os.path.dirname(覆盖文件()) or ".", exist_ok=True)
        tmp = 覆盖文件() + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(表, f, ensure_ascii=False, indent=1)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, 覆盖文件())
    except Exception as e:                               # noqa: BLE001
        return {"ok": False, "err": "写不进去：%s: %s" % (type(e).__name__, e)}
    组, 名 = p.split(".", 1)
    全部[组][名]["值"] = 新                            # 这一句才让「改完立刻生效」
    try:
        import time as _t
        with open(记录文件(), "a", encoding="utf-8") as f:
            f.write(json.dumps({"时间": _t.strftime("%Y-%m-%d %H:%M:%S"),
                                "键": p, "旧": 旧, "新": 新}, ensure_ascii=False) + "\n")
    except Exception:                                    # noqa: BLE001
        pass                                             # 记不上不影响这次改动
    return {"ok": True, "键": p, "旧": 旧, "新": 新}


def 应用覆盖() -> int:
    """启动时把覆盖盖到内存里。返回盖了几项（没有覆盖就是 0）。"""
    n = 0
    for p, v in 读覆盖().items():
        try:
            组, 名 = p.split(".", 1)
            if 组 in 全部 and 名 in 全部[组]:
                全部[组][名]["值"] = _按类型转(p, v)
                n += 1
        except Exception:                                # noqa: BLE001
            continue                                     # 坏值当没有（不因为一行坏档起不来）
    return n


def 改动们(n: int = 200) -> List[Dict]:
    """最近的改动（**新在前**）。读不出来就是空表。"""
    p = 记录文件()
    if not os.path.exists(p):
        return []
    出: List[Dict] = []
    try:
        with open(p, encoding="utf-8") as f:
            for 行 in f:
                行 = 行.strip()
                if not 行:
                    continue
                try:
                    d = json.loads(行)
                except Exception:                        # noqa: BLE001
                    continue
                if isinstance(d, dict):
                    出.append(d)
    except Exception:                                    # noqa: BLE001
        return []
    return list(reversed(出))[:max(1, int(n))]


