def _v(name: str):
    return K[name]["值"]


def 传播(起点: Dict[str, float], 单元向量: Dict[str, Sequence[float]],
         组内成员: Dict[str, Sequence[str]], 组间边: Dict[str, Dict[str, float]],
         α: float = 0.0, β: float = 0.0, γ: float = 0.0, T: int = 0) -> Dict[str, float]:
    """文档那条传播：`组亮 → 成员加成(α)` · `组内(γ)` · `组间(β)`，跑 T 轮。

    ★ 单元 = 组的成员（这里是 cell）与组本身（这里是件）在同一张表里算。
    ★ `组间边[件a][件b]` = 共现强度（0–1）。没有边就不传 —— ⛔ 不凭空造边。
    ★ 池化用 **max**（先粗糙，文档也承认"max 会拍平路径"；等有读数再换软池化）。
    ★★★ 2026-10-17（**实测抓到的真 bug**）：这里原来**每轮只累加、不归一化** ——
      `新[a] += β·w·s[b]` 和 `新[m] += α·亮` 都是纯正反馈，T=4 轮就**指数爆炸**。
      实测：一场 32 轮算下来，单件「重提强化」累计 **+70.9**（被 `min(1.0, …)` 削平）
      ⇒ **所有件直接满格** ⇒ 「提得多记得牢」变成「什么都记牢」，**没有区分**。
      ⇒ 修法：**每轮跑完按最大值归一化到 [0, 1]**。
        ★ 归一化是单调的 ⇒ **`[R]` 取前 k 的排序不变**（那是它唯一的用途）；
        ★★ 而**强化**要的是**绝对量级**，所以必须归一化。
    """
    s = dict(起点)
    for _ in range(int(T)):
        新 = dict(s)
        # ---- 组亮 → 成员加成（软加成，⛔ 不硬补齐）
        for 组, 成员们 in 组内成员.items():
            亮 = max([s.get(组, 0.0)] + [s.get(m, 0.0) for m in 成员们]) if 成员们 else s.get(组, 0.0)
            for m in 成员们:
                新[m] = s.get(m, 0.0) + α * 亮
            if 成员们:
                新[组] = s.get(组, 0.0) + γ * 亮          # 组内传播：成员也把亮度回灌给组
        # ---- 组间（现算边，按 β）
        for a, 边 in 组间边.items():
            for b, w in 边.items():
                if b in s:
                    新[a] = 新.get(a, 0.0) + β * float(w) * s[b]
        # ★★★ **归一化到 [0, 1]**（⛔ 去掉：正反馈会指数爆炸 —— 见 docstring）
        峰 = max(新.values()) if 新 else 0.0
        s = {k: (v / 峰) for k, v in 新.items()} if 峰 > 0 else 新
    return s


def 共现边(图: 图) -> Dict[str, Dict[str, float]]:
    """组间边 = **同场共现**：两个件的 cell 落在同一场里 ⇒ 连一条，权重 = 1/（各自场数的几何平均）。

    ★ 这是唯一"现在就有真数"的边：`待决 §14`（依赖簇阈值）还挂着，共现是无参数的那一档。
    ⛔ 不是"相似度" —— 相似度只用来提候选，不能用它当"经历上同属一件事"的证据（文档明确）。
    """
    场的件: Dict[str, set] = {}
    cell到件 = {}
    for 件id, it in 图.件.items():
        for cid in (it.get("成员") or []):
            cell到件[cid] = 件id
    # ★ 2026-10-17：**同场共现要按「轮距」衰减**。
    #   原来写的是"同场就全连、权 `1/√(na·nb)`" ⇒ 同一场里 4 个件两两全连、权全是 1.0
    #   ⇒ 图几乎**全连通** ⇒ 边的信息量等于零，块内边那 1.0 也被淹掉（真对话实测）。
    #   改成：同一场里**隔得越远越弱** —— 相邻的件（轮距 1）权 ≈ base/2，隔 10 轮 ≈ base/11。
    #   ★ 这仍然是个占位（`待决 §14`）：它不是"依赖"，只是"同场 + 距离"这个最便宜的先验。
    件的轮: Dict[str, Dict[str, List[int]]] = {}      # 件id → {场id: [轮…]}
    for c in 图.cell:
        件id = cell到件.get(c["id"])
        if 件id:
            场的件.setdefault(c["场id"], set()).add(件id)
            件的轮.setdefault(件id, {}).setdefault(c["场id"], []).append(int(c["轮"]))
    次数: Dict[str, set] = {}
    for 场, 件们 in 场的件.items():
        for a in 件们:
            次数.setdefault(a, set()).add(场)

    def _最近轮距(场: str, a: str, b: str) -> int:
        """两件在场里**最近的那两轮**之间隔几轮。挨在一起 ⇒ 1。"""
        ra = 件的轮.get(a, {}).get(场) or []
        rb = 件的轮.get(b, {}).get(场) or []
        if not ra or not rb:
            return 10                                  # 拿不到 ⇒ 当隔得比较远
        return max(1, min(abs(x - y) for x in ra for y in rb))

    边: Dict[str, Dict[str, float]] = {}
    for 场, 件们 in 场的件.items():
        件们 = sorted(件们)
        for i, a in enumerate(件们):
            for b in 件们[i + 1:]:
                na, nb = len(次数.get(a) or ()), len(次数.get(b) or ())
                base = 1.0 / max(1.0, (na * nb) ** 0.5)
                w = base / (1.0 + _最近轮距(场, a, b))   # ★ 轮距衰减
                边.setdefault(a, {})[b] = max(边.get(a, {}).get(b, 0.0), w)
                边.setdefault(b, {})[a] = max(边.get(b, {}).get(a, 0.0), w)
    # ★★ 2026-10-17（作者定 A）：**块内边** —— 同一类 / 同一种情绪的件之间连一条。
    #   它比"同场共现"强（那是碰巧聊到，权 ≤ 1；这是经历上的归类）⇒ 权重取 1.0，用 max 合。
    #   ★ 这就是"猫的两件事"在读取时真的能互相带起来的唯一途径 ——
    #     它们**不是同一件**（不在同一个件里），但同在一个块里。
    W = float(K["块内边权重"]["值"]) if "块内边权重" in K else 1.0
    # ★★★ 2026-10-17（作者定）：**沿「边」**，⛔ 沿"块" —— 块现在是派生视图。
    for e in (getattr(图, "边", []) or []):
        a, b = str(e.get("a")), str(e.get("b"))
        if not a or not b or a == b:
            continue
        边.setdefault(a, {})[b] = max(边.get(a, {}).get(b, 0.0), W)
        边.setdefault(b, {})[a] = max(边.get(b, {}).get(a, 0.0), W)
    return 边


def 回忆(线索: str, 图: 图, 底片目录: str,
         嵌入: Optional[Callable[[Sequence[str]], List[List[float]]]] = None,
         k: Optional[int] = None) -> Dict:
    """返回 `{"件":[{件id, 分数, 强度, 原文们[], 代表原文}], "留痕":[...], "参数":{...}}`。

    ⛔ 只读：不建、不删、不改任何东西。
    """
    k = int(K["k"]["值"] if k is None else k)
    参数 = {"k": k, "α": _v("α"), "β": _v("β"), "γ_传播": _v("γ_传播"), "T": _v("T"),
            "传播加成": _v("传播加成"),
            # ★★ 2026-10-17（作者："不能作为唯一指标"）：权重 = 置信度 ＋ 参与度。
            #   以前只写「置信度（占位）」—— 而它乘上去能摆动 5 倍（0.2→1.0），
            #   比传播项（最多 +λ）大一个量级 ⇒ 一件淡下去的旧件，再像也排不进来。
            "权重": "置信度 × (0.7 + 0.3×参与度)；参与度 = 该件的平均边权，按全场峰归一"}
    if not 图.标记集:
        return {"件": [], "留痕": [], "参数": 参数, "激活": {}, "为什么": "标记集是空的（还没有件）"}

    向量表 = 图.件向量表()
    if not 向量表:
        return {"件": [], "留痕": [], "参数": 参数, "激活": {}, "为什么": "件还没有表示向量"}
    线索向量: List[float] = []
    if 嵌入 is not None and str(线索 or "").strip():
        try:
            # ★★ 2026-10-17 真对话抓到的：原来写的是 `嵌入([..])`，而 `Embedder` **不可调用**
            #   （方法是 `raw_embed`）⇒ TypeError ⇒ 被吞成空向量 ⇒ **起点相似度从来没算过**，
            #   于是 `[R]` 回忆一直只能返回空。⛔ 别再写成 `嵌入(...)`。
            _行 = list(取向量(嵌入, [str(线索)]))
            线索向量 = [float(x) for x in (_行[0] if _行 else [])]
        except Exception as e:                # noqa: BLE001
            线索向量 = []
            参数 = dict(参数 or {})
            参数["嵌入错误"] = "%s: %s" % (type(e).__name__, e)
    if not 线索向量:
        return {"件": [], "留痕": [], "参数": 参数, "激活": {}, "为什么": "拿不到线索的向量"}

    # ---- 起点：相似度 × 权重
    # ★★★ 2026-10-17（作者口径）：**单元是 cell，件只是组**。
    #   原来一件只有一个"池化向量"（首格 → 后来的平均），3–4 格的件被**平均成一个点** ⇒
    #   "这件里到底哪一格对得上"在取件时完全没参与。作者："这不是设计原意"。
    #   现在：① 归档时把**每格的向量**存进 `cell.表示`（以前白算不存）；
    #         ② 件亮初值 ＝ **最亮的那一格**（一件里有几格，只要一格对得上就该想起它）；
    #         ③ 每段原文带**自己的**强度给编写模型（⛔ 一件里所有段同一个数）。
    #   ⚠️ 旧图里 cell 没有向量（那时没存）⇒ 那些件退回「池化向量」那条老路，⛔ 崩。
    格向量 = {str(c["id"]): [float(x) for x in (c.get("表示") or [])]
             for c in 图.cell if (c.get("表示") or [])}
    格相似 = {cid: markset.余弦(线索向量, v) for cid, v in 格向量.items()}

    # ★★ 权重 ＝ **置信度 ＋ 参与度**，⛔ 置信度单打独斗（作者："不是拿出去，而是不能作为唯一指标"）
    #   为什么不能只用置信度：它是 0.2–1.0，乘上去能摆动 **5 倍**，比传播项（最多 +λ）大一个量级
    #   ⇒ 一件淡下去的旧件，再像也排不进来。而文档要的本来就是「共现·参与度」。
    边表 = 共现边(图)
    # ★★ 用**平均边权**，⛔ 边权和：边权和挑出来的是"老枢纽"（件多、边多、每条都很弱），
    #   实测 件-0009（枢纽）在三个问句上都被抬进前 4、把她该想起的那件挤到后面 ——
    #   那正是传播那条已经修过的病（谁连的边多谁赢）。平均边权量的才是"跟谁耦合得紧"。
    度 = {}
    for i in 向量表:
        ws = [float(w) for w in (边表.get(i) or {}).values()]
        度[i] = (sum(ws) / len(ws)) if ws else 0.0
    峰度 = max(度.values()) if 度 else 0.0

    起点: Dict[str, float] = {}
    组内成员: Dict[str, List[str]] = {}
    for i in 向量表:
        conf = float(图.标记集.get(i, 0.0))
        part = (度.get(i, 0.0) / 峰度) if 峰度 > 0 else 0.0
        # ★★ 权重 = 置信度 × (0.7 + 0.3×参与度)
        #   ⛔ 加法版（`0.5·conf + 0.5·part`）试过：`参与度` 一进分子，**老枢纽**就被抬进
        #     前 4（件-0009 在三个问句上都挤掉了该想起的那件）—— 那正是传播那条已经修过的病。
        #   ⇒ 置信度仍是**主标度**（决定量级），参与度只在 30% 以内**修正**它（谁跟谁耦合得紧），
        #     这样"是不是只有置信度说了算"被打破了，而"淡下去的旧件排不进来"也不会被推翻。
        权重 = conf * (0.7 + 0.3 * part)
        员 = [str(c) for c in ((图.件.get(i) or {}).get("成员") or []) if str(c) in 格相似]
        组内成员[i] = 员
        for c in 员:
            起点[c] = float(格相似[c]) * 权重      # ★ 格也用**同一份权重**，否则格会反超件
        首 = (max(格相似[c] for c in 员) if 员
              else markset.余弦(线索向量, 向量表[i]))
        起点[i] = float(首) * 权重

    # ---- 传播（组内：α 给成员加成、γ 回灌给组；组间：β 沿共现边）
    s = 传播(起点, 向量表, 组内成员, 边表,
              α=float(参数["α"]), β=float(参数["β"]),
              γ=float(参数["γ_传播"]), T=int(参数["T"]))

    # ---- ★★★ 终结 ＝ **起点 ＋ 传播加成**（2026-10-17 真数据抓到的严重问题）
    #   病：原来直接拿**传播后的 `s`** 排序，而 `s` 每轮按最大值归一化
    #   ⇒ **谁连的边多谁赢**。实测（27 件 / 77 边）三个真实问句：
    #     Q「楼下那只小的又蹲在花坛边上…」  件-0023（猫/碗）**按起点第 1（0.635）**，
    #        传播后 **掉到第 14**，第 1 名永远是 件-0009「假装没定」（枢纽件）。
    #     我妈 / 碗 两个问句同样：对的件按起点是第 1，传播后掉到 16。
    #   ⇒ 后果不是"少给一件"，而是**她根本取不到该想起的那件事**（场 10 她开场就说
    #     「以前那只是怎么了？我不记得你提过」——而那是喂了两年的猫）。
    #   ⇒ 改法：传播只**加**，⛔ 覆盖起点 —— `终结 = 起点 + λ · 传播 × 峰起点`。
    #     λ=0.3 实测：三个问句对的件都回到**第 1**，而关联件（件-0024 收碗）仍被抬进前 4
    #     （联想要的就是这个，但**不许压过直接匹配**）。λ=1.0 会把"我妈"那句的正确件挤掉。
    λ = float(参数["传播加成"])
    峰 = max((v for i, v in 起点.items() if i in 图.件), default=0.0)
    终 = {i: float(起) + λ * float(s.get(i, 0.0)) * float(峰)
          for i, 起 in 起点.items() if i in 图.件}

    # ---- 取前 k 件
    # ★★★ 2026-10-17（审查抓到）：原来直接 `sorted(s)[:k]`，而 `s` 的起点表是
    #   **所有有向量的件**（含已剪出的）⇒ 剪出件仍能被取回、注入上下文，且 `强度=0`
    #   ⇒「遍历门槛」在读取侧**从来没生效过**（它只被 `markset` 当剪出阈值用）。
    #   ⇒ 只从**标记集**取，且过门槛。剪出件要复活得走 `待观察池` 那条（⛔ 这里偷偷捞）。
    门槛 = float(K件["遍历门槛"]["值"])
    排 = [(i, v) for i, v in 终.items()
          if i in 图.标记集 and float(图.标记集.get(i, 0.0)) >= 门槛]
    排 = sorted(排, key=lambda t: (-t[1], t[0]))[:k]
    if not 排:
        return {"件": [], "留痕": [], "参数": 参数, "激活": 归一(终),
                "为什么": "没有取到件"}

    # ---- 每件取**整组**原文（按区间回底片切）
    底片们: Dict[str, Optional[Dict]] = {}
    import os
    out: List[Dict] = []
    留痕: List[Dict] = []
    for 件id, 分 in 排:
        it = 图.件.get(件id) or {}
        # ★★★ 2026-10-17（作者问：「如果新的记忆和旧记忆有冲突呢？比如之前说不喜欢的食物，
        #   今天试了发现还不错」）⇒ **⛔ 覆盖**：两条都留着，并落一条 `改口` 关系
        #   （新的指向旧的）。取用时**成对带出来**，再按**时间顺序**排 —— 她看到的就是
        #   「以前说不喜欢…… 后来试了觉得还行」，⛔ 只拿到其中一半、把另一半说成没见过。
        #   ⚠️ 只带**一层**伙伴（⛔ 递归）：`A改口B、B改口C` 时取 A 只带 B。
        要取 = [(cid, 件id) for cid in (it.get("成员") or [])]
        for 伙 in 图.修正伙伴(件id):
            for cid in ((图.件.get(伙) or {}).get("成员") or []):
                要取.append((cid, 伙))
        行们: List[tuple] = []          # (场id, 轮, 文本) —— 用来按时间排序
        for cid, 属于 in 要取:
            c = next((x for x in 图.cell if x["id"] == cid), None)
            if c is None:
                continue
            场 = c["场id"]
            if 场 not in 底片们:
                底片们[场] = 读底片(os.path.join(底片目录, 场 + ".json.gz")) or \
                    读底片(os.path.join(底片目录, 场 + ".json"))
            # ★★★ 2026-10-17（审查抓到）：这两半**没有说话人标记**就拼成一行，
            #   而 `writing.py` 的提示词原来断言「都是你自己说过的话」
            #   ⇒ **用户的自述被当成她的第一人称记忆**，而且不报错。
            他 = 切回原文(底片们[场] or {}, c["轮"], "刺激")
            她 = 切回原文(底片们[场] or {}, c["轮"], "她说")
            文本 = (("他：" + 他 + "\n") if 他 else "") + (("她：" + 她) if 她 else "")
            if 文本.strip():
                行们.append((場序(场, c["轮"]), 场, 文本, c, 属于))
        行们.sort(key=lambda t: t[0])
        原文们: List[str] = []
        强度们: List[float] = []
        件强 = float(图.标记集.get(件id, 0.0))
        for _序, 场, 文本, c, 属于 in 行们:
            原文们.append(文本)
            # ★★ 每段带**自己的**强度（2026-10-17）：原来一件里所有段共用一个数，
            #   编写模型就没法知道"哪一段才是这次最贴的那一格"。
            #   ⚠️ 而 `writing.编写提示词` 说的是「0 到 1」—— 以前喂的是 `终结`（可 >1，
            #   最坏 39），⛔ 与提示词不符；现在喂的是该格自己的起点（cos×权重，∈[0,1]）。
            强度们.append(float(起点.get(str(c["id"]), 件强)))
            留痕.append({"件": 属于, "场id": 场, "轮": c["轮"], "起": c["起"], "止": c["止"],
                         "强度": round(float(起点.get(str(c["id"]), 件强)), 3)})
        out.append({"件id": 件id, "分数": float(分),
                    "强度": 件强, "原文们": 原文们, "强度们": 强度们})
    return {"件": out, "留痕": 留痕, "参数": 参数, "激活": 归一(终)}


def 归一(值表: Dict[str, float]) -> Dict[str, float]:
    """压到 `[0,1]`（**除以峰值**，⛔ 改顺序）—— `激活` 要能进逐轮记录、也要能算平均。

    ★ 为什么归一：归档的重提强化按「这一场里的**平均激活**」算（∈[0,1]），
      而 `终结 = 起点 + 传播加成` 可能 > 1。
    """
    峰 = max(值表.values()) if 值表 else 0.0
    if not 峰 or 峰 <= 0:
        return {k: 0.0 for k in 值表}
    return {k: float(v) / float(峰) for k, v in 值表.items()}


def 場序(场id: str, 轮: int):
    """排序键：**先场、后轮**（`场id` 就是 `YYYY-MM-DD-NN`，字典序 = 时间序）。

    ★ 为什么要排：`改口` 的两条必须按时间先后给她看（以前 → 后来）。
    """
    return (str(场id or ""), int(轮 or 0))
