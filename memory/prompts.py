# --------------------------------------------------------------------------- 会话前缀的可编辑覆盖
# ★ 上面那两条 `SYS1` / `SYS2` **永远是默认值**，覆盖单独存盘 ——
#   与 `companion/settings.py` 同一套规矩，理由也一样：
#   · 默认改了要能传下去（存盘里只放"他改过的"，不是整份拷贝）；
#   · 改过的那一份要能看出是改过的，也能一键回到默认。
# ⚠️ 一旦有覆盖，跑的**就不再是"逐字冻结"的那一份**了 —— 这是用户自己的选择，
#   但界面上必须能看见"现在是改过的 / 已恢复默认"。
def prompt_path(path=None):
    """覆盖存哪儿：环境变量优先，其次与凭证同级（与 `settings.yaml` 同一个目录）。"""
    from pathlib import Path as _P
    env = os.environ.get("COMPANION_PROMPT_PATH")
    if path is not None:
        return _P(path)
    if env:
        return _P(env)
    from .config import cred_path
    return cred_path().parent / "prompt.yaml"


def load_session_prompts(path=None):
    """取生效的会话前缀 `(SYS1, SYS2)`。

    ★ 覆盖是**整条替换**，不是追加。前缀的排布与措辞是做过对照的
      （见本文件开头与 `session.py` 的注释），拼接会悄悄改掉那个排布。
    ★ 读不出来（文件坏 / 缺字段）⇒ 回落默认并**吵一声**，不抛：
      提示词坏了不该让 App 起不来，但也不能静默当成"他改的没生效"。
    """
    p = prompt_path(path)
    try:
        if not p.exists():
            return SYS1, SYS2
        data = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
        s1 = str(data.get("sys1") or "").strip()
        s2 = str(data.get("sys2") or "").strip()
        if not s1 or not s2:
            return SYS1, SYS2
        return s1, s2
    except Exception as exc:  # noqa: BLE001
        import sys as _s
        print("[prompts] %s 读不出来（%s），改用默认提示词"
              % (p, type(exc).__name__), file=_s.stderr)
        return SYS1, SYS2


def save_session_prompts(sys1, sys2, path=None):
    """存覆盖。**原子写**（手机上进程随时可能被杀，半截文件会让下次启动读到坏的）。"""
    import tempfile
    p = prompt_path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    body = yaml.safe_dump({"sys1": str(sys1), "sys2": str(sys2)},
                          allow_unicode=True, sort_keys=False)
    fd, tmp = tempfile.mkstemp(dir=str(p.parent), prefix=".prompt-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write("# companion 的提示词覆盖（**整条替换**，不是追加）\n"
                    "# 删掉本文件即回到 `companion/prompts.py` 里的冻结默认。\n")
            f.write(body)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, p)
    finally:
        if os.path.exists(tmp):
            try:
                os.remove(tmp)
            except OSError:
                pass
    return p


def clear_session_prompts(path=None) -> bool:
    """删掉覆盖 ⇒ 回到冻结默认。返回"原本有没有覆盖"。"""
    p = prompt_path(path)
    if p.exists():
        p.unlink()
        return True
    return False


