def 标记(序列: List[Dict], γ: Optional[float] = None, τ: Optional[int] = None,
         手工: Optional[List[Dict]] = None) -> List[Dict]:
    """`②`：`误差 > μ_{t−τ..t−1} + γ·σ` ⇒ 标记。**前 τ 轮不判**（没有窗口）。

    ★★ `手工`：**明确的标记**（用户说"记住这个" / 她自己觉得重要）——
      **无条件进标记，⛔ 过阈值**。这是第三个来源（`REM-SWS §9` 的 reward），
      也是**唯一靠得住的那个**：它⛔ 猜，它是明说的。
    """
    γ = float(K标记["γ"]["值"] if γ is None else γ)
    τ = int(K标记["τ"]["值"] if τ is None else τ)
    out: List[Dict] = []
    for i, e in enumerate(序列):
        x = e.get("误差")
        if x is None or i < τ:
            continue
        窗口 = [序列[j]["误差"] for j in range(max(0, i - τ), i) if 序列[j].get("误差") is not None]
        if not 窗口:
            continue
        阈值 = _均值(窗口) + γ * _标准差(窗口)
        if float(x) > 阈值:
            out.append({"轮": e["轮"], "误差": float(x), "阈值": 阈值,
                        "超出": float(x) - 阈值, "来源": "意外"})
    # ★ 手工标记：**无条件**加（哪怕误差一点都不大）—— 明说的比算出来的可靠
    已 = {int(m["轮"]) for m in out}
    for h in (手工 or []):
        r = int(h.get("轮") or 0)
        if not r:
            continue
        # ★★★ 2026-10-17（审查抓到）：原来 `if r in 已: continue` ⇒ 同一轮若**也被 ② 判成意外**，
        #   来源会留在"意外" ⇒ 完成() 判成非手工档 ⇒ 按普通档衰减、9 场就剪出 ⇒
        #   **「明确说要记住」这条最靠得住的路被悄悄废掉**。⇒ 手工要**覆盖**意外的来源。
        # ★★ 2026-10-17（作者定）：**只有用户明说 `谁=用户` 才算手工档（永不剪出）**；
        #   她自己标的（`谁=她`：调 `remember` 或归档时自报）⇒ `来源=自报`，**按普通档走**。
        #   作者原话：「她自报的给普通，当兜底用」—— 否则她被问一次就能灌满记忆，
        #   而且"永不剪出"这件事就成了她自己说了算。
        源 = "手工" if str(h.get("谁") or "用户") == "用户" else "自报"
        if r in 已:
            for m in out:
                if int(m["轮"]) == r:
                    m["来源"] = 源
                    m["谁"] = str(h.get("谁") or "")
                    m["为什么"] = str(h.get("为什么") or "")
                    break
            continue
        已.add(r)
        out.append({"轮": r, "误差": None, "阈值": None, "超出": None,
                    "来源": 源, "谁": str(h.get("谁") or ""),
                    "为什么": str(h.get("为什么") or "")})
    out.sort(key=lambda m: int(m["轮"]))
    return out


def _池化(向量们: List[List[float]]) -> List[float]:
    """**件**的表示 ＝ 组内成员向量的**平均**（池化）。

    ★★★ 2026-10-17（作者指出"为啥会有这种信息截断"）：原来 `新件(...)` 拿的是**首格**的
    向量、归进时也**从不更新** ⇒ 一个三格的件（"站门口没往里走 / 碗我收了 / …"）只用第一格
    的语义去检索，**后面那几格根本不参与匹配**（"碗"的查询retrieve 不到它）。
    设计里写的是「组亮 ＝ **池化**(成员的传播后表示)」⇒ 这里就是那一步。
    ⚠️ `cell` 自己的向量**没存**（只存件的表示）⇒ 只能在归档时用手里的这几个向量池化；
      要"按成员重算"得先把 cell 向量存下来（见 `待决`）。
    ⚠️ 空列表 ⇒ 返回 `[]`（调用方视为"没有表示"，⛔ 塞一个全 0 向量）。
    """
    们 = [v for v in (向量们 or []) if v]
    if not 们:
        return []
    维 = len(们[0])
    好 = [v for v in 们 if len(v) == 维]
    if not 好:
        return []
    return [sum(float(v[i]) for v in 好) / len(好) for i in range(维)]


