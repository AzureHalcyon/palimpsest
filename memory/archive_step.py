        _向量们: List[List[float]] = []
        for p in ps:
            轮 = int(p["轮"])
            cell = (图.按区间找cell(场id, 轮)
                    or 图.加cell(场id, 轮, int(p.get("起") or 0), int(p.get("止") or 0)))
