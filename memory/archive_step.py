def _摘要(标: List[Dict], 判表: List[Dict]) -> str:
    if not 判表:
        return "这一场没有值得记的地方（没有标记）。"
    行 = ["这一场认出 %d 处：" % len(判表)]
    # ★ 同组的合成一行：`一件含 N 格` 才看得出"一件事"的粒度有没有对。
    组数: Dict[str, List[int]] = {}
    for p in 判表:
        if p.get("归进"):
            行.append("- 第 %d 轮 → 归进 %s" % (p["轮"], p["归进"]))
        else:
            组数.setdefault(str(p.get("组", "u%d" % int(p["轮"]))), []).append(int(p["轮"]))
    for 号, 轮们 in 组数.items():
        if len(轮们) == 1:
            行.append("- 第 %d 轮 → 新建一件" % 轮们[0])
        else:
            行.append("- 第 %s 轮 → 新建**一件（含 %d 格）**"
                      % ("、".join(str(r) for r in 轮们), len(轮们)))
    return "\n".join(行)


def 分堆提示(处们: List[Dict]) -> str:
    """`[10] (b)` 的提示词。**单独拎出来**是为了能拿真数据单独试它（⛔ 把判据埋在流程里）。

    ★★ 2026-10-17（作者：「1 这个，是不是偏松，得测」）：测出来的确**偏松**。
      19 个「合成一件」的件里，32 对组内相似度的中位是 0.562，而"同一场里随机两件事"的
      基线中位是 0.440 ⇒ 有 4 对（12%）**比随机还更像两件事**。最典型的 件-0029：
      第 3 轮「碗和柜子一块清了」＋ 第 5 轮「我妈问周末回不回去」被合成一件，
      而分堆模型自己给的 `说法` 就是一句缝起来的话（「…怎么面对那个空角、**以及**周末
      回去要不要把没说的话说出口」）。⇒ 判据含糊，它就按"话题近"合并。
      ⇒ 收紧成「同一**件具体的事**＝同一个对象 ＋ 同一个动作/场合」，并把
        「同一个话题/同一种心情/同一个人 ⛔ 不算」和「拿不准就分开」写死。
    """
    行 = []
    for p in 处们:
        轮 = int(p.get("轮") or 0)
        上 = str(p.get("上") or "")
        行.append("第 %d 轮：%s%s" % (轮, ("（上一句：「%s」）" % 上) if 上 else "",
                                    str(p.get("文本") or "")))
    return ("下面是我**这一场**说过的几句话（都没归进任何已有的件）。\n\n%s\n\n"
            "请你判断：**这些话里，哪些在讲同一件具体的事**，把它们归成一组。\n\n"
            "● 什么算「同一件」：\n"
            "· 同一个对象 ＋ 同一件**具体发生的事**（同一个场合、同一个动作、同一个念头）。\n"
            "  例：「碗又搁回阳台那个角」和「碗收进柜子里」是同一只碗的两步 ⇒ 算同一件。\n"
            "· ⛔ 只是**同一个话题**、同一种心情、同一个人，**不算**同一件。\n"
            "  例：「我把碗和柜子一块清了」和「我妈打电话问周末回不回去」同一天、都跟家里有关，\n"
            "     但对象和动作都不同 ⇒ **不是一件事，必须分开**。\n"
            "· ⛔ 拿不准 ⇒ **分开**（宁可两件，别合成一件）。\n\n"
            "● 输出要求：\n"
            "· 用【轮号】列成员；\n"
            "· ★ 允许有些话自成一件事（不属于任何组）——⛔ 不要硬把每一条都塞进某组；\n"
            "· 每组的「说法」**只能讲一件事**：⛔ 别用「以及 / 还有 / 另外」把两件事缝在一起。\n\n"
            "只输出 JSON：{\"组\":[{\"成员\":[轮号…],\"说法\":\"…\"}],\"单独成事的\":[轮号…]}"
            % "\n".join(行))


def _本批分堆(llm, 底片数据: Dict, 判表: List[Dict], 进度=None) -> None:
    """`[10]` 的**第二问 (b)**：本批没归进的那些 cell 里，**哪些彼此属于一起** ⇒ 写 `组`。

    ★★ 为什么必须做（真机第 1 场实测抓到的）：草案期间 `图.标记集` **不动**，
      所以"归进"(a) 的候选**在第一批必然全空** ⇒ 若不做 (b)，5 个标记会各自新建一件
      ⇒ **一件 ≠ 一件事**（`流程框架 §四` 那条：一件只有一个 cell），
      `[R]` 的组内 α / 组间 β 全部退化成摆设。
    ★ 判失败 ⇒ **每个单独成组**（保守，⛔ 不猜、也不崩）。

    写进 `判表[*]["组"]`：同组号 ⇒ `完成()` 会把它们合成**一个含多个成员的件**。
    """
    新 = [p for p in 判表 if p.get("新建") and not p.get("归进")]
    for p in 新:
        p.pop("组", None)
    if len(新) <= 1:
        return                              # 只有一处 ⇒ 它自己就是一件事，不用问

    提示 = 分堆提示([{"轮": int(p["轮"]),
                      "文本": _这一处的原文(底片数据, int(p["轮"])),
                      "上": _上一句(底片数据, int(p["轮"]))} for p in 新])
    if 进度:
        进度("phase", "归档：本批分堆（%d 处）" % len(新))
    try:
        msg = llm.chat([{"role": "user", "content": 提示}],
                       fast=True, temp=0.0)   # ★★ temp=0：归档必须**可复算**
        from .llm import parse_json
        d = parse_json(str(msg.get("content") or ""))
    except Exception as e:                   # noqa: BLE001
        for k, p in enumerate(新):
            p["组"] = k                      # 失败 ⇒ 各自成组
            p["分堆说法"] = "分堆失败（%s: %s），各自成件" % (type(e).__name__, e)
        return
    轮到项 = {int(p["轮"]): p for p in 新}
    组 = 0
    if isinstance(d, dict):
        for g in (d.get("组") or []):
            员 = g.get("成员") if isinstance(g, dict) else g
            说 = str((g or {}).get("说法") or "") if isinstance(g, dict) else ""
            真 = [int(m) for m in (员 or []) if str(m).lstrip("-").isdigit() and int(m) in 轮到项]
            if len(真) < 2:
                continue                     # 一组的成员少于 2 ⇒ 不算一组
            for m in 真:
                轮到项[m]["组"] = 组
                轮到项[m]["分堆说法"] = 说
            组 += 1
    for p in 新:                             # 没被分进任何组的 ⇒ 各自成组
        if "组" not in p:
            p["组"] = 组
            组 += 1


def 依赖簇段(轮们, 误差们, 种子数=None, 邻=None):
    """**依赖簇的段**：只吃"这一场有哪些轮 + 每轮的误差"，⛔ 不吃 cell。

    ★ 为什么单独拆出来：**草案阶段这一场的 cell 还没建**（`完成` 才落 cell），
      而"依赖簇没做到才触发手工簇"必须在草案里就判 ⇒ 先按**轮号**分段，
      到 `完成` 时再用段去映射 cell。
    """
    from .knobs import 件 as _K件
    种子数 = int(种子数 or _K件["依赖簇种子数"]["值"])
    邻 = int(邻 if 邻 else _K件["依赖簇邻"]["值"])
    轮们 = sorted({int(r) for r in (轮们 or [])})
    if not 轮们:
        return []
    误 = {}
    for e in (误差们 or []):
        try:
            r, x = int(e.get("轮") or 0), e.get("误差")
        except (TypeError, ValueError):
            continue
        if r and x is not None:
            误[r] = float(x)
    if not 误:
        return []
    种 = sorted(误, key=lambda r: (-误[r], r))[:种子数]
    段s = []
    for r in sorted(种):
        a, b = max(轮们[0], r - 邻), min(轮们[-1], r + 邻)
        if 段s and a <= 段s[-1][1] + 1:
            段s[-1] = (段s[-1][0], max(段s[-1][1], b))
        else:
            段s.append((a, b))
    return 段s


def 算依赖簇(图, 场id: str, 误差们, 种子数=None, 邻=None):
    """**依赖簇**：一场里按**惊讶度**分段（设计：组 ＝ 真正的事件划分，用惊讶度聚）。

    ★★ 2026-10-18（作者）：**依赖簇才该是大头**，手工簇（⑤ 判的件）只在它没做到时补。
      种子 = 这一场误差最高的几轮；种子 ± 邻 轮合成一段 ⇒ 一个组（连续轮）。
      重叠的段合并；组 id 带场号，**可复算**（缓存而已）。
    """
    from .knobs import 件 as _K件
    轮们 = sorted({int(c["轮"]) for c in 图.cell if c["场id"] == 场id})
    段s = 依赖簇段(轮们, 误差们, 种子数=种子数, 邻=邻)
    出 = []
    for n, (a, b) in enumerate(段s, 1):
        员 = [str(c["id"]) for c in 图.cell
              if c["场id"] == 场id and a <= int(c["轮"]) <= b]
        if 员:
            出.append({"id": "组-%s-%02d" % (场id[-2:], n), "来源": "依赖簇",
                       "场id": 场id, "轮起": a, "轮止": b, "成员": 员})
    return 出


def 相似聚类(图, 新格们, 分位=None, 邻居=None, 最小=None, 组上限=None) -> List[Dict]:
    """**依赖簇的第二种形态**：按表示聚类（可跨场）—— 散格将来靠它聚起来。

    ★★ 2026-10-18（作者：「散格可以散，但是得能期望未来什么时候可以聚起来」
      「这些也是依赖簇该做的吧」「东西少聚一起，多了再分裂」）：

    · **阈值交给数据**：取散格两两 cos 的 `相似聚类分位`（0.9）——
      早期格少 ⇒ 分布窄 ⇒ 线低 ⇒ 聚得粗；格多 ⇒ 线抬高 ⇒ 自然分裂；
    · **每格只连最近的 k 个**（`相似聚类邻居数`=2）：⛔ 连"所有够近的对"，
      同质语料下那样会**链式串联**（实测 p95 阈下 870 条边 ⇒ 大半散格串成一个巨组）；
    · **只从本场新格出发**（旧散格之间不主动连）⇒ 每次归档不会把旧散格重聚一遍；
    · 组过小（< 最小格）不出；组过大（> 组上限）也先不出（分裂还没做）。
    """
    import numpy as np
    from .knobs import 件 as K件
    分 = float(K件["相似聚类分位"]["值"] if 分位 is None else 分位)
    邻 = max(1, int(K件["相似聚类邻居数"]["值"] if 邻居 is None else 邻居))
    最 = int(K件["相似聚类最小格"]["值"] if 最小 is None else 最小)
    上 = int(K件["相似聚类组上限"]["值"] if 组上限 is None else 组上限)
    在组 = set()
    for z in (图.组 or []):
        在组.update(str(x) for x in (z.get("成员") or []))
    新 = [c for c in (新格们 or []) if c.get("表示") and str(c["id"]) not in 在组]
    if not 新:
        return []
    新id = {str(c["id"]) for c in 新}
    散 = [c for c in 图.cell
          if c.get("表示") and str(c["id"]) not in 在组 and str(c["id"]) not in 新id]
    if not 散:
        return []
    全部 = 新 + 散
    ids = [str(c["id"]) for c in 全部]
    位置 = {k: i for i, k in enumerate(ids)}
    M = np.asarray([[float(x) for x in c["表示"]] for c in 全部], dtype=float)
    N = np.linalg.norm(M, axis=1, keepdims=True)
    M = M / np.where(N > 0, N, 1.0)
    S = M @ M.T
    np.fill_diagonal(S, -1.0)
    散i = [位置[str(c["id"])] for c in 散]
    if len(散i) >= 2:
        sub = S[np.ix_(散i, 散i)]
        iu = np.triu_indices(len(散i), 1)
        阈 = float(np.percentile(sub[iu], 分 * 100.0))
    else:
        阈 = 0.0
    父 = {k: k for k in ids}

    def 找(x):
        while 父[x] != x:
            父[x] = 父[父[x]]
            x = 父[x]
        return x

    def 并(a, b):
        父[找(a)] = 找(b)

    for i, k in enumerate(ids):
        if k not in 新id:
            continue                    # ★ 只从新格出发
        for j in np.argsort(-S[i])[:邻]:
            j = int(j)
            if S[i, j] >= 阈:
                并(k, ids[j])
    簇: Dict[str, List[str]] = {}
    for k in ids:
        簇.setdefault(找(k), []).append(k)
    出: List[Dict] = []
    for 根, 员们 in sorted(簇.items()):
        if len(员们) < 最 or len(员们) > 上 or not (set(员们) & 新id):
            continue
        场们 = sorted({str(next(c for c in 全部 if str(c["id"]) == m)["场id"]) for m in 员们})
        出.append({"id": "组-相似-%s" % sorted(员们)[0], "来源": "相似",
                   "怎么来的": "相似聚类", "成员": sorted(员们), "场们": 场们})
    return 出


