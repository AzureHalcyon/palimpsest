def 全场标记(序列: List[Dict], γ: float = 1.0) -> List[Dict]:
    """**整场**的 `μ + γσ` —— 只作**兜底**：滑动窗口一个都没标时才用。

    ★★ 为什么要有它（【作者定 2026-10-17】· 读数在 `待决 §24`）：
      滑动窗口（`τ=5`）在**短场次**上几乎没有机会 —— 一场 8 轮只有 3 次判定，
      而两次真机读数（9 轮 / 8 轮）都是 **0 个标记**。
      归档本来就在做「回头再看一遍**这一场**哪几处最意外」⇒ 用同一个公式、窗口换成整场。
    ⚠️ 它**会多标**（全场 σ 把窗口内的局部波动抹平了）⇒ ⛔ 当常规判据用。
    ⚠️ `len < 3` 时 μ/σ 没有意义 ⇒ 直接不判（⛔ 拿两三处硬算出一个阈值）。
    """
    xs = [float(e["误差"]) for e in 序列 if e.get("误差") is not None]
    if len(xs) < 3:
        return []
    mu, sd = _均值(xs), _标准差(xs)
    阈值 = mu + float(γ) * sd
    out: List[Dict] = []
    for e in 序列:
        x = e.get("误差")
        if x is None:
            continue
        if float(x) > 阈值:
            out.append({"轮": e["轮"], "误差": float(x), "阈值": 阈值,
                        "超出": float(x) - 阈值, "来源": "意外", "判法": "全场"})
    out.sort(key=lambda m: int(m["轮"]))
    return out


