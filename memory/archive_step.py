class 底片表(Dict[str, Dict]):
    """`{场id: 底片}`，**缺的那一场第一次被问到才从磁盘读**。

    ★★★ 2026-10-17（"几十场还顶不顶得住"）：`archive_draft` 原来把 `<cache>/底片/` 下的
      底片**全读**一遍，只因为 `_候选行()` 要拿"**候选件的代表 cell 所在那一场**"的原文。
      而场次是线性涨的 ⇒ **每归档一次就 O(全部历史) 解压一遍**（9 场 2.5 MB；几十场十几 MB）。
      ⇒ 改成**按需读一场**，并且读不到就记住（⛔ 同一个场反复试）。
      ⚠️ 读不到**不许崩**：候选行会明说「原文取不到」（见 `_候选行`），⛔ 渲染成空标题。
    """

    def __init__(self, 目录: str, 初始: Optional[Dict[str, Dict]] = None):
        super().__init__(初始 or {})
        self.目录 = str(目录 or "")
        self._读不到: set = set()

    def 取(self, 场id) -> Optional[Dict]:
        k = str(场id or "")
        if not k:
            return None
        if dict.__contains__(self, k):
            return dict.__getitem__(self, k)
        if k in self._读不到:
            return None
        from .film import 读底片
        d = None
        for 名 in (k + ".json.gz", k + ".json"):
            try:
                d = 读底片(os.path.join(self.目录, 名))
            except Exception:                        # noqa: BLE001
                d = None
            if d:
                break
        if not d:
            self._读不到.add(k)
            return None
        self[k] = d
        return d

    def get(self, 场id, default=None):              # noqa: D401 —— 只覆盖 `get`
        d = self.取(场id)
        return default if d is None else d


def _候选行(图: 图, 候选: List[tuple], 底片们: Dict[str, Dict],
           每件几段: Optional[int] = None) -> str:
    """给 `⑤` 看的候选：**每件列出几段原文**（⛔ 只列 `代表` 那一格）。

    ★★★ 2026-10-17（作者指出）：`代表` 只是"这件用哪一格当锚点/标题"的记账字段，
      ⛔ 是内容。原来这里**只渲染代表那一格** ⇒ 一个件的关键说法常常**不在代表上**
      （实测：`件-0026` 的代表是「站门口没往里走」，而"碗我收了"是它的另一格）⇒
      `⑤` 看不到真内容 ⇒ **改口/归进 都是瞎的**。
    ⇒ 现在：代表排最前，其余按（场、轮）补上，最多 `knobs.判.候选每件几段` 段。
    """
    上限 = int(K判["候选每件几段"]["值"] if 每件几段 is None else 每件几段)
    行 = []
    for 件id, 分 in 候选:
        it = 图.件.get(件id) or {}
        代表 = str(it.get("代表") or "")
        段们 = []
        for cid in (it.get("成员") or []):
            c = next((x for x in 图.cell if x["id"] == cid), None)
            if c is None:
                continue
            底 = 底片们.get(str(c.get("场id") or ""))
            # ★ 取不到就**明说取不到**，⛔ 拿空字符串假装它是空的（那会让"没标题的件"逼着模型新建）
            文 = _这一处的原文(底, c["轮"]) if 底 else ""
            段们.append((str(cid), c, 文, "" if 底 else "（原文取不到：%s）" % str(c.get("场id") or "?")))
        if not 段们:
            行.append("%s（像 %.2f）：（这件没有任何成员原文）" % (件id, float(分)))
            continue
        段们.sort(key=lambda t: (0 if t[0] == 代表 else 1,
                                 str(t[1].get("场id") or ""), int(t[1].get("轮") or 0)))
        首 = 段们[0]
        行.append("%s（像 %.2f）：「%s」%s" % (件id, float(分), 首[2][:110], 首[3]))
        for _cid, _c, 文, 缺 in 段们[1:上限]:
            行.append("    └ 同件另一处：「%s」%s" % (文[:110], 缺))
    return "\n".join(行) if 行 else "（一件都没有）"


def 草案(底片数据: Dict, 图: 图, llm, 场id: str,
         嵌入: Optional[Callable[[Sequence[str]], List[List[float]]]] = None,
         其他底片: Optional[Dict[str, Dict]] = None, 进度: Optional[Callable] = None,
         对话: Optional[List[dict]] = None,
         ) -> Dict:
    """只**算**，⛔ 不动图（用户按「完成」之前，池子一字不动）。"""
    # ⚠️ ⛔ 写成 `dict(其他底片 or {})`：那会把 `底片表` 的"按需读"**拷平成普通 dict**
    #   （于是又变回全读 —— 而且看不出来）。它本来就是 dict 子类，直接用。
