        #   归进时把来源带上 ⇒ 手工的格子并进一个普通件 ⇒ 那个件也跟着变牢（单向）。
        图.归进(件id, cell["id"], vec, 来源=str(p.get("来源") or "意外"))
        # ⚠️ 「冷成员被拉起」这一条**暂时传空**：标记集 的键是**件**，而「成员」是 **cell**，
