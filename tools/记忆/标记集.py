"""标记集：提候选件 · 强化 · 衰减。

★ 这三块是「还没写，但写不出来？不是」的那一类 —— 纯算法，不依赖训练。
  判据与来历：`docs/流程框架.md` §3.2 · §四 · `docs/研究/REM-SWS-机制参考.md` ⑧

数据结构（都不落盘，是运行时的字典）：
    标记集   = {件id: confidence ∈ [0,1]}      ← 当前"活着的件"
    件向量表 = {件id: [float, ...]}            ← 件的代表那句的嵌入（1024 维）

★ 一条口头规矩：**只动 confidence，⛔ 删任何件**。
  掉下去的只是"剪出标记集"，件本身还在图里（`记忆层 §3 ④` 层2）。
"""
import io, json, math, os, sys, urllib.request

# ---------------- 旋钮（先给值，待标定；见 docs/流程框架.md §五） ----------------
K = 5              # 提候选件取几个
增量 = 0.05         # 强化一次加多少（抄 remnic）
拉起到 = 0.25       # 冷成员被拉起的目标（★ 刚好过可用线 0.2）
每窗口 = 0.1        # 每过一个窗口掉多少（抄 remnic）
地板 = 0.1          # 掉到这儿就不再掉（抄 remnic）
遍历门槛 = 0.2      # 低于它就不参与回忆（抄 remnic）


def 余弦(a, b):
    """两向量的余弦。任一为零向量 ⇒ 0（⛔ 让 0/0 抛异常，那会让整批崩）。"""
    na = math.sqrt(sum(x * x for x in a))
    nb = math.sqrt(sum(x * x for x in b))
    if na == 0.0 or nb == 0.0:
        return 0.0
    return sum(x * y for x, y in zip(a, b)) / (na * nb)


def 提候选件(线索向量, 件向量表, 标记集=None, k=K):
    """从【标记集里的件】中取 k 个候选（相似度 ＝ 余弦）。

    ★ 相似度在这里是正当的 —— 它只"提候选/排序"，⛔ 不"定去留"（去留归 `⑤` 判）。
    ★ 只从标记集里取：已剪出去的件⛔ 参与候选。
    返回 [(件id, 分数), …]，按分数降序，最多 k 个。
    """
    池 = list(标记集.keys()) if 标记集 is not None else list(件向量表.keys())
    分 = [(i, 余弦(线索向量, 件向量表[i])) for i in 池 if i in 件向量表]
    分.sort(key=lambda t: (-t[1], t[0]))        # ★ 同分按 id 定序 ⇒ 跨进程可复现
    return 分[:k]


def 强化(标记集, 归进的件=None, 新建的件=None, 冷成员=(), 增量_=增量, 拉起=拉起到):
    """`⑤` 判完后的两段 ④ 层1：写标记集。

    · 归进的件  ⇒ 该件 +增量（上限 1.0）
    · 新建的件  ⇒ 进标记集，confidence = 1.0
    · 冷成员    ⇒ **拉到 max(当前, 拉起)**  ← 【作者定：第二次就强化到能用上就行】
      ⚠️ 这一条是"低频重要"的活路：旧的不被拉起，"第二次被提起"就永远不成立。

    ★ 就地改 标记集 并返回它（调用方通常直接接着用）。
    """
    if 新建的件 is not None:
        标记集[新建的件] = 1.0
    if 归进的件 is not None:
        标记集[归进的件] = min(1.0, 标记集.get(归进的件, 1.0) + 增量_)
    for i in (冷成员 or ()):
        标记集[i] = max(标记集.get(i, 0.0), 拉起)   # ★ 只往上拉，⛔ 往下按
    return 标记集


def 衰减(标记集, 窗口数=1, 衰减率=每窗口, 底=地板):
    """④ 层2 的长期维护：每过一个窗口 −衰减率；到地板不再掉。

    ★ **⛔ 删件** —— 掉下去的只是"剪出标记集"，件还在图里（下次被碰到还能拉起）。
    返回 (新标记集, 被剪出去的件id 列表)。两者都要给调用方：剪出去的进"待观察池"。
    """
    新 = {}
    剪出 = []
    for i, c in 标记集.items():
        c2 = max(底, c - 衰减率 * 窗口数)
        新[i] = c2
        if c2 < 遍历门槛:
            剪出.append(i)
    return 新, 剪出


# ---------------- 嵌入（要网络；只在真要跑的时候用） ----------------

def 嵌入(文本们, 模型="qwen3.7-text-embedding", 批量=20):
    """调阿里云的嵌入端点。★ 批量 ≤ 20（实测上限）。"""
    E = {}
    p = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                     "..", ".local", "接入凭证.env")
    p = os.path.normpath(p)
    if os.path.exists(p):
        for ln in open(p, encoding="utf-8"):
            ln = ln.strip()
            if ln and not ln.startswith("#") and "=" in ln:
                a, b = ln.split("=", 1)
                E[a.strip()] = b.strip()
    基 = E.get("ALIYUN_MAAS_BASE_URL", "").rstrip("/")
    键 = E.get("ALIYUN_MAAS_API_KEY", "")
    if not 基 or not 键:
        raise RuntimeError("缺 ALIYUN_MAAS_BASE_URL / ALIYUN_MAAS_API_KEY")
    出 = []
    for i in range(0, len(文本们), 批量):
        块 = 文本们[i:i + 批量]
        体 = {"model": 模型, "input": 块}
        r = urllib.request.Request(基 + "/embeddings", data=json.dumps(体).encode(),
                                   headers={"Authorization": "Bearer " + 键,
                                            "Content-Type": "application/json"})
        d = json.loads(urllib.request.urlopen(r, timeout=120).read().decode())
        出.extend(x["embedding"] for x in d["data"])
    return 出


# ---------------- 自测（⛔ 联网） ----------------

def _自测():
    坏 = 0

    def 断言(名, 条件, 实际=None):
        nonlocal 坏
        if 条件:
            print("  ok   %s" % 名)
        else:
            坏 += 1
            print("  FAIL %s   实际=%r" % (名, 实际))

    # 余弦
    断言("正交 ⇒ 0", abs(余弦([1, 0], [0, 1])) < 1e-9)
    断言("相同 ⇒ 1", abs(余弦([1, 2], [1, 2]) - 1.0) < 1e-9)
    断言("零向量 ⇒ 0（⛔ 抛异常）", 余弦([0, 0], [1, 1]) == 0.0)

    # 提候选件：线索最像 件2
    表 = {"件1": [1.0, 0.0], "件2": [0.0, 1.0], "件3": [0.7, 0.7]}
    候选 = 提候选件([0.1, 1.0], 表, k=2)
    断言("提候选件取 2 个", len(候选) == 2, 候选)
    断言("第 1 个是 件2", 候选[0][0] == "件2", 候选)

    # 只从标记集里取
    候选 = 提候选件([0.1, 1.0], 表, 标记集={"件1": 0.5}, k=5)
    断言("只从标记集挑", [c[0] for c in 候选] == ["件1"], 候选)

    # 强化
    集 = {"件1": 0.5, "件2": 0.1, "件3": 0.6}
    强化(集, 归进的件="件1", 新建的件="件9", 冷成员=["件2", "件3"])
    断言("归进 ⇒ +0.05", abs(集["件1"] - 0.55) < 1e-9, 集["件1"])
    断言("新建 ⇒ 1.0", 集["件9"] == 1.0, 集["件9"])
    断言("冷成员 0.1 ⇒ 拉到 0.25", abs(集["件2"] - 0.25) < 1e-9, 集["件2"])
    断言("已 0.6 的⛔ 被按下去", abs(集["件3"] - 0.6) < 1e-9, 集["件3"])

    # 强化上限
    集 = {"甲": 0.99}
    强化(集, 归进的件="甲")
    断言("强化上限 1.0", 集["甲"] == 1.0, 集["甲"])

    # 衰减
    集 = {"a": 0.5, "b": 0.15, "c": 0.05}
    新, 剪 = 衰减(集, 窗口数=1)
    断言("0.5 ⇒ 0.4", abs(新["a"] - 0.4) < 1e-9, 新["a"])
    断言("0.15 ⇒ 到地板 0.1", abs(新["b"] - 0.1) < 1e-9, 新["b"])
    断言("已 0.05 ⇒ ⛔ 往下掉", abs(新["c"] - 0.1) < 1e-9, 新["c"])
    断言("剪出的是 b/c（a 衰减后 0.4 仍在线上）", sorted(剪) == ["b", "c"], 剪)

    # 衰减 2 窗口
    新, _ = 衰减({"a": 0.5}, 窗口数=2)
    断言("2 窗口 ⇒ 0.3", abs(新["a"] - 0.3) < 1e-9, 新["a"])

    # 跨进程可复现：同分按 id 定序
    表2 = {"B": [1, 0], "A": [1, 0]}
    候选 = 提候选件([1, 0], 表2, k=2)
    断言("同分按 id 定序", [c[0] for c in 候选] == ["A", "B"], 候选)

    print("\n%s" % ("全部通过" if 坏 == 0 else "有 %d 处不过" % 坏))
    return 坏


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    sys.exit(1 if _自测() else 0)
